/**
 * Virtual /.well-known/josh endpoint.
 */
final class Joshternet_Endpoint {
	const OPTION_ENABLED  = 'joshternet_enabled';
	const OPTION_IDENTITY = 'joshternet_identity';

	/**
	 * Register endpoint handling.
	 *
	 * The plugin deliberately avoids writing files or modifying web-server
	 * configuration. If the host routes the origin-root request to WordPress,
	 * WordPress can answer it directly.
	 *
	 * @return void
	 */
	public static function register() {
		add_action( 'parse_request', array( __CLASS__, 'maybe_serve' ), 0 );
	}

	/**
	 * Serve the Joshternet declaration for the current origin.
	 *
	 * @return void
	 */
	public static function maybe_serve() {
		if ( ! self::is_endpoint_request() ) {
			return;
		}

		if ( Joshternet_Origin::shares_origin_with_main_site() ) {
			return;
		}

		if ( ! self::is_enabled() ) {
			return;
		}

		$method = isset( $_SERVER['REQUEST_METHOD'] )
			? strtoupper( sanitize_text_field( wp_unslash( $_SERVER['REQUEST_METHOD'] ) ) )
			: 'GET';

		if ( ! in_array( $method, array( 'GET', 'HEAD' ), true ) ) {
			status_header( 405 );
			header( 'Allow: GET, HEAD' );
			header( 'Content-Type: application/json; charset=UTF-8' );
			header( 'X-Content-Type-Options: nosniff' );
			exit;
		}

		$body = wp_json_encode( self::declaration(), JSON_UNESCAPED_SLASHES );

		status_header( 200 );
		header( 'Content-Type: application/json; charset=UTF-8' );
		header( 'Cache-Control: public, max-age=300, must-revalidate' );
		header( 'X-Content-Type-Options: nosniff' );

		if ( 'HEAD' !== $method ) {
			echo $body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON generated by wp_json_encode().
		}

		exit;
	}

	/**
	 * Whether the request is exactly the canonical origin-root endpoint.
	 *
	 * RFC-JOSH-0002 defines no trailing slash, additional path components,
	 * query parameters, or alternate endpoint locations.
	 *
	 * @return bool
	 */
	private static function is_endpoint_request() {
		if ( empty( $_SERVER['REQUEST_URI'] ) || ! is_string( $_SERVER['REQUEST_URI'] ) ) {
			return false;
		}

		// Compared only to a fixed path; sanitize_text_field() would mangle URI paths.
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
		$request_uri = wp_unslash( $_SERVER['REQUEST_URI'] );

		if ( ! is_string( $request_uri ) || false !== strpos( $request_uri, '?' ) ) {
			return false;
		}

		$path = wp_parse_url( $request_uri, PHP_URL_PATH );

		return is_string( $path ) && '/.well-known/josh' === $path;
	}

	/**
	 * Whether the current origin has opted into Joshternet participation.
	 *
	 * @return bool
	 */
	public static function is_enabled() {
		return (bool) get_option( self::OPTION_ENABLED, false );
	}

	/**
	 * Build the RFC-JOSH-0002 version 1 declaration.
	 *
	 * Participation is represented by publishing a valid declaration. Josh
	 * identity is optional and remains separate from participation.
	 *
	 * @return array<string, int|bool>
	 */
	public static function declaration() {
		$declaration = array( 'version' => 1 );
		$identity    = (string) get_option( self::OPTION_IDENTITY, 'undeclared' );

		if ( 'affirmed' === $identity ) {
			$declaration['josh'] = true;
		} elseif ( 'declined' === $identity ) {
			$declaration['josh'] = false;
		}

		return $declaration;
	}
}
